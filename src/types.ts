export type Color = "purple" | "coral" | "green" | "blue" | "yellow";
export type User = { id: string; name: string; email: string; image?: string | null };
export type Room = {
  kind?: "group" | "direct";
  peerId?: string;
  peerHandle?: string;
  canMessage?: boolean;
  id: string;
  name: string;
  description: string;
  color: Color;
  ownerId: string;
  image?: string | null;
  inviteCode?: string;
  memberCount: number;
  lastText?: string;
  lastAt?: string;
  unread: number;
};
export type RSVP = {
  userId: string;
  name: string;
  status: "yes" | "maybe" | "no";
};
export type Plan = {
  id: string;
  roomId: string;
  creatorId: string;
  title: string;
  description: string;
  location: string;
  startsAt: string;
  endsAt: string;
  color: Color;
  cancelled: boolean;
  roomName?: string;
  rsvps: RSVP[];
};
export type Message = {
  id: string;
  text: string;
  eventId?: string;
  replyTo?: string;
  replyText?: string;
  editedAt?: string;
  pendingStatus?: "sending" | "failed";
  deleted?: boolean;
  pinned?: boolean;
  senderId: string;
  senderName: string;
  senderImage?: string | null;
  attachment?: { id: string; name: string; mime: string; size: number; width?: number; height?: number; url?: string };
  createdAt: string;
  reactions: { userId: string; emoji: string }[];
};
export type Boot = { user: User; rooms: Room[]; events: Plan[] };
